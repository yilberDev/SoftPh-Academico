"""Password reset tokens of residents (HU-016).

Only SHA-256(token) is stored. A token is pending while it is neither used nor
revoked (and valid until expires_at). The generated pending_user_marker is
user_id while pending and NULL afterwards: its UNIQUE index allows at most one
pending reset per user, so a new request must revoke the previous one first.
"""

from datetime import datetime

from sqlalchemy import CHAR, BigInteger, CheckConstraint, Computed, ForeignKey, Index, UniqueConstraint, text
from sqlalchemy.dialects.mysql import DATETIME
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.sql.elements import conv

from app.db.base import Base


class PasswordResetToken(Base):
    __tablename__ = "password_reset_tokens"
    __table_args__ = (
        CheckConstraint("expires_at > created_at", name="expires_after_creation"),
        # A token ends either used or revoked, never both.
        CheckConstraint("used_at IS NULL OR revoked_at IS NULL", name="used_or_revoked"),
        UniqueConstraint("pending_user_marker", name=conv("uq_password_reset_tokens_pending_user")),
        # Foreign key index and rate limit (requests of a user within a window).
        Index("ix_password_reset_tokens_user_id_created_at", "user_id", "created_at"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    user_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("users.id", ondelete="RESTRICT"))
    token_hash: Mapped[str] = mapped_column(CHAR(64), unique=True)
    created_at: Mapped[datetime] = mapped_column(DATETIME(fsp=6), server_default=text("CURRENT_TIMESTAMP(6)"))
    expires_at: Mapped[datetime] = mapped_column(DATETIME(fsp=6))
    used_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    revoked_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    # Generated by MySQL; never written by the application.
    pending_user_marker: Mapped[int | None] = mapped_column(
        BigInteger, Computed("CASE WHEN used_at IS NULL AND revoked_at IS NULL THEN user_id END", persisted=False)
    )
