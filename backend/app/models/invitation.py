"""Resident invitations (HU-003) and residences (created by HU-019).

An administrator invites a resident to an apartment (units.id). The invitation
reserves the apartment while it is PENDING; the residence (resident_units) is
only created when the resident activates the account (HU-019).
"""

from datetime import datetime
from enum import StrEnum

from sqlalchemy import CHAR, BigInteger, CheckConstraint, Computed, ForeignKey, String, UniqueConstraint, text
from sqlalchemy.dialects.mysql import DATETIME, SMALLINT, TINYINT
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.sql.elements import conv

from app.db.base import Base


class InvitationStatus(StrEnum):
    # Only PENDING → USED (HU-019) and PENDING → EXPIRED exist; never back to PENDING.
    PENDING = "PENDING"
    USED = "USED"
    EXPIRED = "EXPIRED"


class DeliveryStatus(StrEnum):
    # Result of the last email delivery attempt, independent of the status.
    PENDING = "PENDING"
    SENT = "SENT"
    FAILED = "FAILED"


VALIDITY_DAYS_MIN = 1
VALIDITY_DAYS_MAX = 30


def _in_list(column: str, values: type[StrEnum]) -> str:
    return f"{column} IN ({', '.join(repr(v.value) for v in values)})"


class ResidentInvitation(Base):
    """Invitation for one resident (user_id) to one apartment (unit_id).

    Only SHA-256(token) is stored. The generated markers are NULL unless the
    invitation is PENDING, so their UNIQUE indexes allow at most one pending
    invitation per apartment and per user.
    """

    __tablename__ = "resident_invitations"
    __table_args__ = (
        CheckConstraint(
            f"validity_days BETWEEN {VALIDITY_DAYS_MIN} AND {VALIDITY_DAYS_MAX}", name="validity_days_range"
        ),
        CheckConstraint(_in_list("status", InvitationStatus), name="status_valid"),
        CheckConstraint(_in_list("delivery_status", DeliveryStatus), name="delivery_status_valid"),
        CheckConstraint("send_attempts >= 0", name="send_attempts_non_negative"),
        CheckConstraint("expires_at > created_at", name="expires_after_creation"),
        CheckConstraint("(status = 'USED') = (used_at IS NOT NULL)", name="used_at_matches_status"),
        CheckConstraint("delivery_status <> 'SENT' OR last_sent_at IS NOT NULL", name="sent_has_timestamp"),
        UniqueConstraint("pending_unit_marker", name=conv("uq_resident_invitations_pending_unit")),
        UniqueConstraint("pending_user_marker", name=conv("uq_resident_invitations_pending_user")),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    # SHA-256 of the token; the token itself is never stored. Rotated on resend.
    token_hash: Mapped[str] = mapped_column(CHAR(64), unique=True)
    user_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("users.id", ondelete="RESTRICT"), index=True)
    unit_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("units.id", ondelete="RESTRICT"), index=True)
    invited_by_user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="RESTRICT"), index=True
    )
    validity_days: Mapped[int] = mapped_column(TINYINT(unsigned=True))
    status: Mapped[str] = mapped_column(String(20), server_default=text("'PENDING'"))
    delivery_status: Mapped[str] = mapped_column(String(20), server_default=text("'PENDING'"))
    send_attempts: Mapped[int] = mapped_column(SMALLINT(unsigned=True), server_default=text("'0'"))
    created_at: Mapped[datetime] = mapped_column(DATETIME(fsp=6), server_default=text("CURRENT_TIMESTAMP(6)"))
    expires_at: Mapped[datetime] = mapped_column(DATETIME(fsp=6))
    used_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    last_sent_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    # Generated by MySQL; never written by the application.
    pending_unit_marker: Mapped[int | None] = mapped_column(
        BigInteger, Computed("CASE WHEN status = 'PENDING' THEN unit_id END", persisted=False)
    )
    pending_user_marker: Mapped[int | None] = mapped_column(
        BigInteger, Computed("CASE WHEN status = 'PENDING' THEN user_id END", persisted=False)
    )


class ResidentUnit(Base):
    """Residence: a resident living in an apartment. Created by HU-019 on activation.

    One active resident per apartment and one active apartment per resident
    (ended_at IS NULL), guaranteed by UNIQUE indexes on generated markers.
    """

    __tablename__ = "resident_units"
    __table_args__ = (
        CheckConstraint("ended_at IS NULL OR ended_at >= started_at", name="ended_after_start"),
        UniqueConstraint("active_unit_marker", name=conv("uq_resident_units_active_unit")),
        UniqueConstraint("active_user_marker", name=conv("uq_resident_units_active_user")),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    user_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("users.id", ondelete="RESTRICT"), index=True)
    unit_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("units.id", ondelete="RESTRICT"), index=True)
    # An invitation produces at most one residence.
    invitation_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("resident_invitations.id", ondelete="RESTRICT"), unique=True
    )
    started_at: Mapped[datetime] = mapped_column(DATETIME(fsp=6))
    ended_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    active_unit_marker: Mapped[int | None] = mapped_column(
        BigInteger, Computed("CASE WHEN ended_at IS NULL THEN unit_id END", persisted=False)
    )
    active_user_marker: Mapped[int | None] = mapped_column(
        BigInteger, Computed("CASE WHEN ended_at IS NULL THEN user_id END", persisted=False)
    )
