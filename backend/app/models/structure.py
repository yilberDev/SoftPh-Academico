"""Physical structure of the Urbanización San Joaquín (HU-013).

Bloque → Torre → Apartamento. Each level stores only its number; the visible
identifier ("B1-TO2-APTO-104") is always derived (app.core.unit_labels) and is
never stored. Every foreign key points to a stable id, so renumbering a level
never rewrites other rows.
"""

from datetime import datetime

from sqlalchemy import BigInteger, CheckConstraint, Computed, ForeignKey, UniqueConstraint, text
from sqlalchemy.dialects.mysql import DATETIME, INTEGER
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.sql.elements import conv

from app.db.base import Base

# number while the row is not soft-deleted, NULL afterwards. A UNIQUE index on
# it (alone or after the parent id) allows any number of deleted rows but only
# one active row per number, so deleted numbers can be reused.
ACTIVE_NUMBER_EXPRESSION = "CASE WHEN deleted_at IS NULL THEN number END"


def _number_column() -> Mapped[int]:
    # INT UNSIGNED: its maximum is a technical limit of the column, not a domain rule.
    return mapped_column(INTEGER(unsigned=True))


def _active_number_marker() -> Mapped[int | None]:
    # Generated by MySQL; never written by the application.
    return mapped_column(INTEGER(unsigned=True), Computed(ACTIVE_NUMBER_EXPRESSION, persisted=False))


def _version_column() -> Mapped[int]:
    # Optimistic locking: every change increments it.
    return mapped_column(INTEGER(unsigned=True), server_default=text("'1'"))


def _created_at() -> Mapped[datetime]:
    return mapped_column(DATETIME(fsp=6), server_default=text("CURRENT_TIMESTAMP(6)"))


def _updated_at() -> Mapped[datetime]:
    return mapped_column(
        DATETIME(fsp=6), server_default=text("CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)")
    )


def _common_checks() -> tuple[CheckConstraint, CheckConstraint]:
    return (
        CheckConstraint("number >= 1", name="number_positive"),
        CheckConstraint("version >= 1", name="version_positive"),
    )


class Block(Base):
    """Bloque: B1, B2, ..."""

    __tablename__ = "blocks"
    __table_args__ = (
        *_common_checks(),
        UniqueConstraint("active_number_marker", name=conv("uq_blocks_active_number")),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    number: Mapped[int] = _number_column()
    version: Mapped[int] = _version_column()
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()
    deleted_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    active_number_marker: Mapped[int | None] = _active_number_marker()


class Tower(Base):
    """Torre: TO1, TO2, ... The same number can exist in different blocks."""

    __tablename__ = "towers"
    __table_args__ = (
        *_common_checks(),
        UniqueConstraint("block_id", "active_number_marker", name=conv("uq_towers_block_active_number")),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    # Immutable: a tower never moves to another block.
    block_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("blocks.id", ondelete="RESTRICT"), index=True)
    number: Mapped[int] = _number_column()
    version: Mapped[int] = _version_column()
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()
    deleted_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    active_number_marker: Mapped[int | None] = _active_number_marker()


class Unit(Base):
    """Unidad residencial (apartamento): APTO-1, APTO-104, ...

    units.id is the stable reference for residents, invitations, charges and
    payments (later HUs). The same number can exist in different towers.
    """

    __tablename__ = "units"
    __table_args__ = (
        *_common_checks(),
        UniqueConstraint("tower_id", "active_number_marker", name=conv("uq_units_tower_active_number")),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    # Immutable: an apartment never moves to another tower.
    tower_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("towers.id", ondelete="RESTRICT"), index=True)
    number: Mapped[int] = _number_column()
    version: Mapped[int] = _version_column()
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()
    deleted_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    active_number_marker: Mapped[int | None] = _active_number_marker()
