from datetime import datetime
from enum import StrEnum

from sqlalchemy import BigInteger, CheckConstraint, Computed, SmallInteger, String, text
from sqlalchemy.dialects.mysql import DATETIME
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class UserRole(StrEnum):
    # Domain values as they appear in the academic document.
    ADMINISTRADOR = "ADMINISTRADOR"
    RESIDENTE = "RESIDENTE"


class UserStatus(StrEnum):
    PENDING_ACTIVATION = "PENDING_ACTIVATION"
    ACTIVE = "ACTIVE"
    DISABLED = "DISABLED"


def _in_list(column: str, values: type[StrEnum]) -> str:
    return f"{column} IN ({', '.join(repr(v.value) for v in values)})"


# 1 for an active, non-deleted administrator; NULL for every other row.
# A UNIQUE index on it allows many NULLs but only one 1, so the database
# guarantees at most one active administrator (HU-001, decision D3).
ACTIVE_ADMINISTRATOR_EXPRESSION = (
    "CASE WHEN role = 'ADMINISTRADOR' AND status = 'ACTIVE' AND deleted_at IS NULL THEN 1 ELSE NULL END"
)


class User(Base):
    """Account for both roles (HU-001; residents are added by later HUs)."""

    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint(_in_list("role", UserRole), name="role_valid"),
        CheckConstraint(_in_list("status", UserStatus), name="status_valid"),
        # An active account always has a password.
        CheckConstraint("status <> 'ACTIVE' OR password_hash IS NOT NULL", name="active_has_password"),
        # Extra defense for the canonical email (normalize_email() is the rule;
        # TRIM() only removes U+0020 spaces). ASCII: one byte per character.
        CheckConstraint("email = LOWER(email) AND email = TRIM(email)", name="email_canonical"),
        CheckConstraint("CHAR_LENGTH(email) = LENGTH(email)", name="email_ascii"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    # Exact (binary, NO PAD) comparison: the same identity as the login throttle.
    email: Mapped[str] = mapped_column(String(254, collation="utf8mb4_0900_bin"), unique=True)
    # NULL until the account is activated (residents are invited without a password).
    password_hash: Mapped[str | None] = mapped_column(String(255))
    full_name: Mapped[str] = mapped_column(String(150))
    document_number: Mapped[str | None] = mapped_column(String(20), unique=True)
    phone: Mapped[str | None] = mapped_column(String(20))
    role: Mapped[str] = mapped_column(String(20))
    status: Mapped[str] = mapped_column(String(20))
    created_at: Mapped[datetime] = mapped_column(
        DATETIME(fsp=6), server_default=text("CURRENT_TIMESTAMP(6)")
    )
    updated_at: Mapped[datetime] = mapped_column(
        DATETIME(fsp=6),
        server_default=text("CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)"),
    )
    # Soft delete: the row (and its email) is kept to preserve history.
    deleted_at: Mapped[datetime | None] = mapped_column(DATETIME(fsp=6))
    # Generated by MySQL; never written by the application.
    active_administrator_marker: Mapped[int | None] = mapped_column(
        SmallInteger, Computed(ACTIVE_ADMINISTRATOR_EXPRESSION, persisted=False), unique=True
    )
